// Build step (no dependencies). Run after changing any app file or text:
//
//   node tools/build.mjs
//
// 1. Bundles every texts/*.json into texts/library.js, the built-in example texts.
// 2. Writes the list of app files and a content hash into sw.js, so installed
//    copies of the app (PWA) pick up the new version and work offline.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// ---------------------------------------------------------------- 1. texts
const textsDir = join(root, 'texts');
const files = readdirSync(textsDir).filter((f) => f.endsWith('.json')).sort();
const docs = files.map((f) => {
  const doc = JSON.parse(readFileSync(join(textsDir, f), 'utf8'));
  if (!doc.meta || !doc.meta.id) throw new Error(`${f}: meta.id is required for bundled texts`);
  return doc;
});
writeFileSync(
  join(textsDir, 'library.js'),
  '// GENERATED by tools/build.mjs from texts/*.json — do not edit by hand.\n' +
    'export default ' + JSON.stringify(docs) + ';\n'
);
console.log(`Bundled ${docs.length} text(s): ${files.join(', ')}`);

// ---------------------------------------------------------------- 2. service worker
function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const assets = [
  'index.html',
  'manifest.webmanifest',
  'docs/template.json',
  ...['css', 'js', 'icons'].flatMap((d) => walk(join(root, d)).map((p) => relative(root, p))),
  'texts/library.js',
]
  .map((p) => p.split('\\').join('/'))
  .sort();

const hash = createHash('sha256');
for (const a of assets) hash.update(a).update(readFileSync(join(root, a)));
const version = hash.digest('hex').slice(0, 12);

const swPath = join(root, 'sw.js');
let sw = readFileSync(swPath, 'utf8');
sw = sw
  .replace(/^const VERSION = .*;$/m, `const VERSION = '${version}';`)
  .replace(/^const ASSETS = [\s\S]*?\];$/m, 'const ASSETS = ' + JSON.stringify(['./', ...assets], null, 2) + ';');
writeFileSync(swPath, sw);
console.log(`sw.js: version ${version}, ${assets.length + 1} files`);
