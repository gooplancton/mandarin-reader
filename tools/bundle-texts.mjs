// Bundles every texts/*.json into texts/library.js so the app also works when
// index.html is opened straight from disk (file://, where fetch() is blocked).
// Usage: node tools/bundle-texts.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'texts');
const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const docs = files.map((f) => {
  const doc = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  if (!doc.meta || !doc.meta.id) throw new Error(`${f}: meta.id is required for bundled texts`);
  return doc;
});
const out =
  '// GENERATED by tools/bundle-texts.mjs from texts/*.json — do not edit by hand.\n' +
  'window.MR_LIBRARY = (window.MR_LIBRARY || []).concat(' +
  JSON.stringify(docs) +
  ');\n';
writeFileSync(join(dir, 'library.js'), out);
console.log(`Bundled ${docs.length} text(s): ${files.join(', ')}`);
